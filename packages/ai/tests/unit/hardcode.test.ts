import { mkdirSync, symlinkSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { checkHardcodedModels, KIT_ALLOW, LEGACY_WARN } from "#hardcode.js";
import { kitDir } from "#kit.js";
import { checkTokenomics } from "#tokenomics.js";
import { isPinnedId, MODEL_FAMILIES } from "#model-names.js";
import { AGENT, put, SKILL, tempDir } from "./helpers.js";

/** A project with an `.agents/` dir; returns the root. */
function project(files: Record<string, string> = {}): string {
  const root = tempDir();
  mkdirSync(join(root, ".agents"), { recursive: true });
  for (const [rel, text] of Object.entries(files)) put(root, rel, text);
  return root;
}

function scan(root: string): string[] {
  return checkHardcodedModels(root, join(root, ".agents")).map((i) => `${i.path}: ${i.message}`);
}

const policy = (hardcode: string, providers = ""): string => `---\nschema: 1\n${providers}${hardcode}---\n\nProse may name gpt-5 freely.\n`;

describe("model-names families", () => {
  const positives: Record<string, string[]> = {
    "claude ids": ["claude-opus-4-1", "claude-sonnet-4", "claude-haiku-3-5", "claude-fable-5", "claude-3-5-sonnet"],
    "claude names with a version": ["Sonnet 4.5", "opus-5", "Haiku 3"],
    "gpt and o-series": ["gpt-5.1", "GPT4", "gpt-4o-mini", "o3-mini", "o1-pro", "o4-preview"],
    others: ["gemini-2.5-pro", "grok-4", "composer-2", "llama-3.1", "mistral-large", "deepseek-r1", "qwen3-coder"],
  };

  it("has a test sample for every family", () => {
    expect(Object.keys(positives).sort()).toEqual(MODEL_FAMILIES.map((f) => f.family).sort());
  });

  for (const [family, names] of Object.entries(positives)) {
    it(`flags ${family}`, () => {
      for (const name of names) {
        const root = project({ "AGENTS.md": `Use ${name} here.\n` });
        const found = scan(root);
        expect(found, name).toHaveLength(1);
        expect(found[0], name).toContain(`model name "${name}"`);
      }
    });
  }

  it("leaves product names, bare words and file names alone", () => {
    const clean = [
      "Use Claude Code or claude-code to run it.",
      "Read GEMINI.md and CLAUDE.md and claude-md.",
      "A sonnet, an opus and a haiku are poems.",
      "The foo1-mini and zk-grok words are not models.",
      "o1 and o3 alone are not models, gpt- neither.",
    ];
    for (const line of clean) expect(scan(project({ "AGENTS.md": `${line}\n` })), line).toEqual([]);
  });

  it("drops trailing sentence punctuation from the reported name", () => {
    const found = scan(project({ "AGENTS.md": "We pinned claude-opus-4.\n" }));
    expect(found).toEqual([expect.stringContaining('model name "claude-opus-4"')]);
  });
});

describe("checkHardcodedModels scope", () => {
  it("scans skills, agents, commands, top-level notes, root files and Cursor rules", () => {
    const root = project({
      ".agents/skills/alpha/SKILL.md": `${SKILL("alpha")}\nPin gpt-5.\n`,
      ".agents/agents/beta.md": `${AGENT("beta")}\nPrefer gemini-2.5-pro.\n`,
      ".agents/commands/run.md": "---\ndescription: Runs.\n---\n\nUse grok-4.\n",
      ".agents/personas.md": "Persona on llama-3.1.\n",
      "AGENTS.md": "Root uses deepseek-r1.\n",
      ".cursor/rules/project.mdc": "---\nalwaysApply: true\n---\nRule uses qwen3-coder.\n",
    });
    const paths = scan(root).map((line) => line.split(":")[0]);
    expect(paths.sort()).toEqual(
      [
        ".agents/agents/beta.md",
        ".agents/commands/run.md",
        ".agents/personas.md",
        ".agents/skills/alpha/SKILL.md",
        ".cursor/rules/project.mdc",
        "AGENTS.md",
      ].sort(),
    );
  });

  it("never scans the policy files, sidecars, licences, notices, setup log or dependencies", () => {
    const text = "Names gpt-5 and claude-opus-4.\n";
    const root = project({
      ".agents/tokenomics.md": policy(""),
      ".agents/tokenomics.template.md": text,
      ".agents/tokenomics.defaults.md": text,
      ".agents/agents/beta.kit.md": text,
      ".agents/THIRD_PARTY_NOTICES.md": text,
      ".agents/skills/alpha/LICENSE-upstream.md": text,
      ".agents/setup-log/plan.md": text,
      ".agents/skills/alpha/node_modules/x/README.md": text,
      ".agents/skills/alpha/script.sh": text,
    });
    expect(scan(root)).toEqual([]);
  });

  it("skips generated files by their marker, on line 2 (frontmatter) or line 1 (HTML)", () => {
    const marker = "generated by zedkit-ai sync from .agents/agents/beta.md and .agents/tokenomics.md; do not edit";
    const root = project({
      ".agents/agents/beta.md": `---\n# ${marker}\nname: beta\nmodel: gpt-5\n---\nBody gpt-5.\n`,
      ".agents/commands/run.md": `<!-- ${marker} -->\nUse grok-4.\n`,
    });
    expect(scan(root)).toEqual([]);
  });

  it("does not skip a file that only mentions the marker words later", () => {
    const root = project({ ".agents/agents/beta.md": "---\nname: beta\n---\n\ngenerated by zedkit-ai sync\nUse gpt-5.\n" });
    expect(scan(root)).toHaveLength(1);
  });

  it("reads CLAUDE.md linked to AGENTS.md once", () => {
    const root = project({ "AGENTS.md": "Uses gpt-5.\n" });
    symlinkSync("AGENTS.md", join(root, "CLAUDE.md"));
    expect(scan(root)).toEqual([expect.stringContaining("AGENTS.md:1")]);
  });

  it("reads a real CLAUDE.md as its own file", () => {
    const root = project({ "AGENTS.md": "Fine.\n", "CLAUDE.md": "Uses gpt-5.\n" });
    expect(scan(root)).toEqual([expect.stringContaining("CLAUDE.md:1")]);
  });

  it("follows a linked skills dir once and survives a link loop", () => {
    const root = project({ "shared/alpha/SKILL.md": "Uses gpt-5.\n" });
    symlinkSync("../shared", join(root, ".agents/skills"));
    symlinkSync("..", join(root, "shared/loop"));
    expect(scan(root)).toEqual([expect.stringContaining(".agents/skills/alpha/SKILL.md:1")]);
  });

  it("scans root files only beside a `.agents` dir, never next to an arbitrary directory", () => {
    const root = tempDir();
    put(root, "AGENTS.md", "Uses gpt-5.\n");
    put(root, ".cursor/rules/project.mdc", "Uses gpt-5.\n");
    put(root, "scratch/agents/beta.md", AGENT("beta"));
    put(root, "scratch/personas.md", "Uses grok-4.\n");
    expect(checkHardcodedModels(root, join(root, "scratch")).map((i) => i.path)).toEqual(["scratch/personas.md:1"]);
  });

  it("returns nothing for a missing or empty project", () => {
    expect(checkHardcodedModels(tempDir(), join(tempDir(), "nope"))).toEqual([]);
    expect(scan(project())).toEqual([]);
  });
});

describe("checkHardcodedModels reports", () => {
  it("prints one issue per file and name, at the first line, with the fix hint", () => {
    const root = project({ "AGENTS.md": "ok\nUse gpt-5.\nAgain GPT-5 and gpt-4o.\n" });
    const found = checkHardcodedModels(root, join(root, ".agents"));
    expect(found.map((i) => i.path)).toEqual(["AGENTS.md:2", "AGENTS.md:3"]);
    expect(found[0]?.message).toBe(
      'model name "gpt-5" outside tokenomics.md (move it there, or mark the line with <!-- zk:model-ok -->)',
    );
  });

  it("reports the same name again in another file", () => {
    const root = project({ "AGENTS.md": "gpt-5\n", ".agents/personas.md": "gpt-5\n" });
    expect(scan(root)).toHaveLength(2);
  });
});

describe("inline marker and allow_paths", () => {
  it("keeps a name on a marked line or right after a marker line", () => {
    const root = project({
      "AGENTS.md": [
        "Same line gpt-5 <!-- zk:model-ok -->",
        "<!-- zk:model-ok -->",
        "Line below grok-4.",
        "",
        "Too far gemini-2.5-pro.",
        "# zk:model-ok",
        "Yaml-style comment llama-3.1.",
      ].join("\n"),
    });
    expect(scan(root)).toEqual([expect.stringContaining('"gemini-2.5-pro"')]);
  });

  it("a policy that names a model in hardcode.* passes the policy check and the scan together", () => {
    const text = policy("hardcode:\n  allow_paths: ['docs/claude-opus-9/**']\n  extra_patterns: ['acme-\\d+']\n");
    expect(checkTokenomics(text)).toEqual([]);
    const root = project({ ".agents/tokenomics.md": text, "docs/claude-opus-9/notes.md": "gpt-5\n", "AGENTS.md": "Nothing here.\n" });
    expect(scan(root)).toEqual([]);
  });

  it("a later unmarked use still counts when the first use was marked", () => {
    const root = project({ "AGENTS.md": "gpt-5 <!-- zk:model-ok -->\n\nelse gpt-5\n" });
    expect(scan(root)).toEqual([expect.stringContaining("AGENTS.md:3")]);
  });

  it("skips paths matched by allow_paths, relative to the root or to .agents", () => {
    const root = project({
      ".agents/tokenomics.md": policy(
        "hardcode:\n  allow_paths: ['.agents/skills/notes/**', 'agents/*.md', 'docs/**/AGENTS.md', 'AGENTS.md']\n",
      ),
      ".agents/skills/notes/SKILL.md": "gpt-5\n",
      ".agents/agents/beta.md": "gpt-5\n",
      ".agents/agents/deep/gamma.md": "gpt-5\n",
      "AGENTS.md": "gpt-5\n",
      ".agents/personas.md": "gpt-5\n",
    });
    // `*` stays inside one folder, so agents/deep/gamma.md is not covered.
    expect(scan(root).map((line) => line.split(":")[0])).toEqual([".agents/agents/deep/gamma.md", ".agents/personas.md"]);
  });

  it("lets a folder pattern cover everything under it, and `**` cross folders", () => {
    const root = project({
      ".agents/tokenomics.md": policy("hardcode:\n  allow_paths: ['skills/a', 'agents/**']\n"),
      ".agents/skills/a/SKILL.md": "gpt-5\n",
      ".agents/skills/a/deep/x.md": "gpt-5\n",
      ".agents/skills/ab/SKILL.md": "gpt-5\n",
      ".agents/agents/deep/g.md": "gpt-5\n",
    });
    expect(scan(root).map((line) => line.split(":")[0])).toEqual([".agents/skills/ab/SKILL.md"]);
  });

  it("accepts model-shaped paths and patterns in the allowlist itself", () => {
    const root = project({
      ".agents/tokenomics.md": policy(
        "hardcode:\n  allow_paths: ['skills/gpt-5-notes/**', 'docs/claude-opus-4.md']\n  extra_patterns: ['zeta-\\d+[\\w.-]*']\n",
      ),
      ".agents/skills/gpt-5-notes/SKILL.md": "gpt-5\n",
      "AGENTS.md": "Plain text, and zeta-12 is caught by the project pattern.\n",
    });
    expect(scan(root)).toEqual([expect.stringContaining('model name "zeta-12"')]);
  });

  it("applies the allowlist while tokenomics.md has other errors", () => {
    const root = project({
      ".agents/tokenomics.md": policy("hardcode:\n  allow_paths: ['AGENTS.md']\nbogus_key: 1\n"),
      "AGENTS.md": "gpt-5\n",
    });
    expect(scan(root)).toEqual([]);
  });

  it("falls back to no settings when tokenomics.md is not parseable", () => {
    const root = project({ ".agents/tokenomics.md": "no frontmatter at all\n", "AGENTS.md": "gpt-5\n" });
    expect(scan(root)).toHaveLength(1);
  });

  it("ignores malformed settings instead of throwing", () => {
    const root = project({
      ".agents/tokenomics.md": policy("hardcode:\n  allow_paths: 7\n  extra_patterns: ['(', 12]\n  scan_nested: yes please\n"),
      "AGENTS.md": "gpt-5\n",
    });
    expect(scan(root)).toHaveLength(1);
  });
});

describe("project-declared names", () => {
  const cells = (model: string): string =>
    `providers:\n  cursor:\n    build:\n      standard: { model: ${model}, effort: medium }\n`;

  it("flags every id-shaped model pinned in a cell, matched whole and case-insensitively", () => {
    const root = project({
      ".agents/tokenomics.md": policy("", cells("acme-fast-7")),
      "AGENTS.md": "Use ACME-FAST-7 here. acme-fast-70 and my-acme-fast-7 are other words.\n",
    });
    expect(scan(root)).toEqual([expect.stringContaining('model name "ACME-FAST-7"')]);
  });

  it("does not flag `inherit` or a letters-only alias such as fast", () => {
    for (const model of ["inherit", "fast", "opus"]) {
      const root = project({ ".agents/tokenomics.md": policy("", cells(model)), "AGENTS.md": `Be ${model}, inherit and fast.\n` });
      expect(scan(root), model).toEqual([]);
    }
  });

  it("tells id-shaped values from plain aliases", () => {
    expect(["acme-7", "v2", "a.b", "p:q", "x/y", "t@1"].every(isPinnedId)).toBe(true);
    expect(["inherit", "fast", "opus", "", 7, undefined].some(isPinnedId)).toBe(false);
  });

  it("applies the project's own patterns on top of the built-in ones", () => {
    const root = project({
      ".agents/tokenomics.md": policy("hardcode:\n  extra_patterns: ['zeta-\\d+']\n"),
      "AGENTS.md": "Uses ZETA-12 and gpt-5.\n",
    });
    expect(scan(root)).toHaveLength(2);
  });
});

describe("nested AGENTS.md", () => {
  const files = {
    "AGENTS.md": "Fine.\n",
    "packages/a/AGENTS.md": "Nested gpt-5.\n",
    "packages/a/dist/AGENTS.md": "Built gpt-5.\n",
    "packages/a/node_modules/x/AGENTS.md": "Dep gpt-5.\n",
    "packages/a/README.md": "Not a source gpt-5.\n",
  };

  it("is off by default", () => {
    expect(scan(project(files))).toEqual([]);
  });

  it("scans nested AGENTS.md with scan_nested, still skipping build output and dependencies", () => {
    const root = project({ ...files, ".agents/tokenomics.md": policy("hardcode:\n  scan_nested: true\n") });
    expect(scan(root)).toEqual([expect.stringContaining("packages/a/AGENTS.md:1")]);
  });

  it("does not count the root file twice", () => {
    const root = project({ "AGENTS.md": "gpt-5\n", ".agents/tokenomics.md": policy("hardcode:\n  scan_nested: true\n") });
    expect(scan(root)).toHaveLength(1);
  });
});

describe("legacy model-routing.md", () => {
  it("warns at the top of .agents, with real ids in it, until D4 drops the file", () => {
    expect(LEGACY_WARN).toEqual(["model-routing.md"]);
    const root = project({ ".agents/model-routing.md": "| fast | claude-haiku-4-5 | low |\n| deep | gpt-5 | high |\n" });
    const found = scan(root);
    expect(found).toHaveLength(2);
    expect(found.every((line) => line.startsWith(".agents/model-routing.md:") && line.includes("warning:") && line.includes("legacy .agents/model-routing.md"))).toBe(true);
  });

  it("is only exempt as the one legacy file, not as a name anywhere", () => {
    const root = project({
      ".agents/model-routing.md": "gpt-5\n",
      ".agents/skills/alpha/model-routing.md": "gpt-5\n",
      ".agents/model-routing.kit.md": "gpt-5\n",
      ".agents/model-routing-notes.md": "gpt-5\n",
    });
    const paths = scan(root).map((line) => line.split(":")[0]).sort();
    expect(paths).toEqual([".agents/model-routing-notes.md", ".agents/model-routing.md", ".agents/skills/alpha/model-routing.md"]);
    const top = scan(root).filter((line) => line.startsWith(".agents/model-routing.md:"));
    expect(top).toHaveLength(1);
    expect(top[0]).toContain("warning:");
  });

  it("warns on the legacy file and still flags other files as errors", () => {
    const root = project({ ".agents/model-routing.md": "gpt-5\n", "AGENTS.md": "gpt-5\n" });
    const found = scan(root);
    expect(found).toEqual([
      expect.stringContaining(".agents/model-routing.md:1: warning:"),
      expect.stringContaining("AGENTS.md:1: model name \"gpt-5\""),
    ]);
  });

  it("still warns when the legacy file is a symlink whose realpath sits outside .agents", () => {
    const root = project();
    put(root, "hop/model-routing.md", "gpt-5\n");
    symlinkSync(join(root, "hop/model-routing.md"), join(root, ".agents/model-routing.md"));
    const found = scan(root);
    expect(found).toEqual([expect.stringContaining(".agents/model-routing.md:1: warning:")]);
  });

  it("still warns when agentsDir is a symlink (canonical path, not relative-to-alias)", () => {
    const root = project({ ".agents/model-routing.md": "gpt-5\n" });
    const alias = tempDir();
    symlinkSync(join(root, ".agents"), join(alias, ".agents"));
    const found = checkHardcodedModels(root, join(alias, ".agents")).map((i) => `${i.path}: ${i.message}`);
    expect(found.some((line) => line.includes("warning:") && line.includes("legacy .agents/model-routing.md"))).toBe(true);
  });
});

