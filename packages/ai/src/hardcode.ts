import { existsSync, readdirSync, readFileSync, realpathSync, statSync } from "node:fs";
import { basename, join, relative, sep } from "node:path";
import { tryCatch } from "@zedtech/zedkit-core";
import { escapeRegExp, isPinnedId, MODEL_NAME_SOURCE } from "./model-names.js";
import { listRepoFiles } from "./scan.js";
import { parseTokenomics } from "./tokenomics.js";
import type { Issue } from "./validate.js";

/** Write this on the line, or the line above, to keep a model name that has to stay. */
export const MODEL_OK_MARKER = "zk:model-ok";

/**
 * Top-level `.agents/model-routing.md` is still scanned, but hits are
 * warnings with a deprecation line (the migration to `tokenomics.md` exists).
 * Drop this list when D4 stops accepting the legacy file, two minors later.
 */
export const LEGACY_WARN = ["model-routing.md"] as const;

/** True when `fileReal` is the project's `.agents/model-routing.md`, even via symlink. */
function isLegacyRoutingFile(fileReal: string, agentsDir: string): boolean {
  return LEGACY_WARN.some((legacy) => {
    const named = tryCatch(() => realpathSync(join(agentsDir, legacy)));
    return named.ok && named.value === fileReal;
  });
}

/**
 * Kit skills that name a model in benchmark text. They are shipped verbatim,
 * so a consumer with the `full` preset must not have to allow them by hand.
 * Globs are relative to the agents dir; `zk-` copies are the adopt aliases.
 */
export const KIT_ALLOW = ["skills/ponytail-gain/**", "skills/ponytail-help/**", "skills/zk-ponytail-gain/**", "skills/zk-ponytail-help/**"];

// Never scanned, by file name wherever they sit.
const SKIP_NAMES = new Set(["tokenomics.md", "tokenomics.template.md", "tokenomics.defaults.md", "THIRD_PARTY_NOTICES.md"]);
const SKIP_DIRS = new Set(["node_modules", "setup-log"]);
// First lines of a file written by `zedkit-ai sync`: the marker is a YAML
// comment on line 2 (after `---`) or an HTML comment on line 1.
const GENERATED = /^(?:#|<!--)\s*generated by zedkit-ai sync/;

type Config = { allow: string[]; extra: RegExp[]; pinned: string[]; nested: boolean };

const strings = (value: unknown): string[] =>
  Array.isArray(value) ? value.filter((item): item is string => typeof item === "string") : [];
const asObject = (value: unknown): Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value) ? (value as Record<string, unknown>) : {};

// Read the project's scanner settings straight from the file, without
// requiring it to be valid: `validate` reports a bad `tokenomics.md` on its
// own, and an allowlist or pattern must still apply while it is being fixed.
function readConfig(agentsDir: string): Config {
  const config: Config = { allow: [], extra: [], pinned: [], nested: false };
  const file = join(agentsDir, "tokenomics.md");
  const text = tryCatch(() => readFileSync(file, "utf8"));
  if (!text.ok) return config;
  const layer = parseTokenomics(text.value);
  if (!layer.ok) return config;
  const hardcode = asObject(layer.value.hardcode);
  config.allow = strings(hardcode.allow_paths);
  config.nested = hardcode.scan_nested === true;
  for (const source of strings(hardcode.extra_patterns)) {
    const compiled = tryCatch(() => new RegExp(source, "gi"));
    if (compiled.ok) config.extra.push(compiled.value);
  }
  // Every id-shaped model the project pinned in a cell is a name too.
  for (const policy of Object.values(asObject(layer.value.providers))) {
    for (const row of Object.values(asObject(policy))) {
      for (const cell of Object.values(asObject(row))) {
        const model = asObject(cell).model;
        if (isPinnedId(model)) config.pinned.push(model);
      }
    }
  }
  return config;
}

// `**` crosses folders, `*` and `?` stay inside one. A pattern naming a
// folder also covers everything under it.
function globToRegExp(glob: string): RegExp {
  const body = glob.replace(/^\.\//, "").replace(/\/+$/, "");
  let source = "";
  for (let i = 0; i < body.length; i++) {
    const char = body.charAt(i);
    if (char === "*" && body.charAt(i + 1) === "*") {
      const slash = body.charAt(i + 2) === "/";
      source += slash ? "(?:.*/)?" : ".*";
      i += slash ? 2 : 1;
    } else if (char === "*") source += "[^/]*";
    else if (char === "?") source += "[^/]";
    else source += escapeRegExp(char);
  }
  return new RegExp(`^${source}(?:/.*)?$`);
}

const posix = (path: string): string => path.split(sep).join("/");

// Real files only: a link is followed once, a loop is cut by its real path.
function walk(dir: string, seen: Set<string>, out: string[]): void {
  const real = tryCatch(() => realpathSync(dir));
  if (!real.ok || seen.has(real.value)) return;
  seen.add(real.value);
  const entries = tryCatch(() => readdirSync(dir));
  if (!entries.ok) return;
  for (const name of entries.value.sort()) {
    const full = join(dir, name);
    const stat = tryCatch(() => statSync(full));
    if (!stat.ok) continue;
    if (stat.value.isDirectory()) {
      if (!SKIP_DIRS.has(name)) walk(full, seen, out);
    } else if (stat.value.isFile()) out.push(full);
  }
}

const isSource = (file: string): boolean => {
  const name = basename(file);
  return /\.(?:md|mdc)$/.test(name) && !name.endsWith(".kit.md") && !SKIP_NAMES.has(name) && !name.startsWith("LICENSE");
};

const isScannable = (file: string): boolean => isSource(file) && statSync(file, { throwIfNoEntry: false })?.isFile() === true;

// Sources only: skills, subagents, commands and top-level notes of the
// agents dir, the root instruction files, Cursor rules, and (opt-in) nested
// AGENTS.md. Build output, dependencies and the setup log are not sources.
function sourceFiles(projectRoot: string, agentsDir: string, nested: boolean): string[] {
  const files: string[] = [];
  for (const sub of ["agents", "commands", "skills"]) {
    const dir = join(agentsDir, sub);
    if (existsSync(dir)) walk(dir, new Set(), files);
  }
  const top = tryCatch(() => readdirSync(agentsDir));
  for (const name of top.ok ? top.value.sort() : []) {
    const full = join(agentsDir, name);
    if (statSync(full, { throwIfNoEntry: false })?.isFile() === true) files.push(full);
  }
  // Root files belong to a project only when the dir is its `.agents/`; any
  // other dir (the kit, a scratch tree) has no root to scan.
  if (basename(agentsDir) !== ".agents") return files.filter(isScannable);
  for (const name of ["AGENTS.md", "CLAUDE.md"]) files.push(join(projectRoot, name));
  const rules = join(projectRoot, ".cursor", "rules");
  const ruleNames = tryCatch(() => readdirSync(rules));
  for (const name of ruleNames.ok ? ruleNames.value.sort() : []) files.push(join(rules, name));
  if (nested) {
    for (const path of listRepoFiles(projectRoot)) {
      if (basename(path) === "AGENTS.md" && path.includes("/")) files.push(join(projectRoot, path));
    }
  }
  return files.filter(isScannable);
}

const trim = (name: string): string => name.replace(/[.-]+$/, "");

/**
 * Find model names written outside `tokenomics.md`: the built-in id-shaped
 * families, every id-shaped model the project pinned in its cells, and the
 * project's `hardcode.extra_patterns`. One issue per distinct (file, name),
 * at its first unmarked line. A line (or the one above) holding
 * `zk:model-ok` is kept, `hardcode.allow_paths` globs (relative to the
 * project root or to the agents dir) are skipped, and so are files written
 * by `sync`. Hits in top-level `model-routing.md` are warnings, see {@link LEGACY_WARN}.
 * Paths are `<file>:<line>`, relative to `projectRoot`.
 */
export function checkHardcodedModels(projectRoot: string, agentsDir: string): Issue[] {
  const run = tryCatch(() => {
    const config = readConfig(agentsDir);
    const allow = [...KIT_ALLOW.map((glob) => ({ glob, base: "agents" as const })), ...config.allow.map((glob) => ({ glob, base: "any" as const }))].map(
      (entry) => ({ ...entry, regex: globToRegExp(entry.glob) }),
    );
    const patterns = [
      new RegExp(MODEL_NAME_SOURCE, "gi"),
      ...config.pinned.map((id) => new RegExp(`(?<![\\w-])${escapeRegExp(id)}(?![\\w-])`, "gi")),
      ...config.extra,
    ];
    const issues: Issue[] = [];
    const done = new Set<string>();
    for (const file of sourceFiles(projectRoot, agentsDir, config.nested)) {
      const real = realpathSync(file);
      if (done.has(real)) continue;
      done.add(real);
      const rootRel = posix(relative(projectRoot, file));
      const agentsRel = posix(relative(agentsDir, file));
      if (allow.some((entry) => (entry.base === "any" && entry.regex.test(rootRel)) || entry.regex.test(agentsRel))) continue;
      const lines = readFileSync(file, "utf8").split(/\r?\n/);
      if (GENERATED.test(lines[0] ?? "") || GENERATED.test(lines[1] ?? "")) continue;
      const warn = isLegacyRoutingFile(real, agentsDir);
      const names = new Set<string>();
      lines.forEach((line, index) => {
        if (line.includes(MODEL_OK_MARKER) || (lines[index - 1] ?? "").includes(MODEL_OK_MARKER)) return;
        for (const pattern of patterns) {
          for (const match of line.matchAll(pattern)) {
            const name = trim(match[0]);
            if (name === "" || names.has(name.toLowerCase())) continue;
            names.add(name.toLowerCase());
            issues.push({
              path: `${rootRel}:${index + 1}`,
              message: warn
                ? `warning: model name "${name}" outside tokenomics.md (legacy .agents/model-routing.md; copy its rows into tokenomics.md then delete it — this file will fail validate two minors after this release)`
                : `model name "${name}" outside tokenomics.md (move it there, or mark the line with <!-- ${MODEL_OK_MARKER} -->)`,
            });
          }
        }
      });
    }
    return issues;
  });
  return run.ok ? run.value : [{ path: projectRoot, message: `cannot scan for model names: ${run.error.message}` }];
}
