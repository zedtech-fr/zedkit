#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { rewriteUiImports } from "./rewrite-ui-imports.mjs";
import { generateThemePayload } from "./theme-payload.mjs";
import { expectedRegistryThemeFromStyles } from "./theme-tokens.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const uiSrc = join(root, "packages/ui/src");
const i18nSrc = join(root, "packages/i18n/src");
const generatedDir = join(root, "registry/ui");
const outDir = join(root, "apps/docs/public/r");

/** UI bricks published in the first registry slice (#187). */
const REGISTRY_UI_FILES = ["badge.tsx", "button.tsx", "dialog.tsx", "drawer.tsx", "drawer-non-modal.tsx", "drawer-non-modal-context.tsx", "drawer-non-modal-effects.ts", "drawer-panel-classes.ts", "drawer-parts.tsx", "drawer-portal.tsx", "drawer-vaul.tsx", "drawer-meta.tsx", "overlay-modal.ts", "theme-scope.tsx", "confirm-dialog.tsx", "status-dot.tsx", "checkmark.tsx", "updated-ago.tsx", "status-label.tsx", "progress-bar.tsx", "alert.tsx", "type-roles.ts", "typography.tsx", "detail-panel.tsx", "tabs.tsx", "skeleton.tsx", "sonner.tsx", "card.tsx", "surface.tsx", "parallax.tsx", "parallax-types.ts", "wizard-steps.tsx", "separator.tsx", "label.tsx", "app-shell.tsx", "card-skeleton.tsx", "offline-note.tsx", "use-online-status.ts", "use-narrow-viewport.ts", "icon-button.tsx", "icon-label.tsx", "ui-provider.tsx", "messages.ts", "updated-ago-client.tsx", "updated-ago-format.ts", "empty-state.tsx", "error-state.tsx", "spinner.tsx"];

function stageTransformedSources() {
  rmSync(generatedDir, { recursive: true, force: true });
  mkdirSync(generatedDir, { recursive: true });
  for (const file of REGISTRY_UI_FILES) {
    const raw = readFileSync(join(uiSrc, file), "utf8");
    writeFileSync(join(generatedDir, file), rewriteUiImports(raw), "utf8");
  }
  for (const file of ["create-messages-context.tsx", "format-message.ts"]) {
    const raw = readFileSync(join(i18nSrc, file), "utf8");
    writeFileSync(join(generatedDir, file), rewriteUiImports(raw), "utf8");
  }
  writeFileSync(
    join(generatedDir, "README.md"),
    `# Registry UI sources (shadcn copy path)

Generated by \`pnpm registry:build\` from \`packages/ui/src\` (imports rewritten for
consumer \`@/\` paths). Committed so \`npx shadcn@latest add zedtech-fr/zedkit/<brick>\`
can read sources from GitHub. Do not edit by hand. CI runs
\`bash scripts/check-registry-ui-drift.sh\` after \`pnpm registry:build\`.
`,
  );
}

/**
 * Sync registry.json css/cssVars from the package stylesheet: per-brick
 * slices from theme-tokens.mjs, the theme item whole from
 * theme-payload.mjs. Hand-edited values in registry.json are overwritten
 * here — edit styles.css (or the expectations) instead.
 */
function syncRegistryTheme() {
  const registryPath = join(root, "registry.json");
  const registry = JSON.parse(readFileSync(registryPath, "utf8"));
  const cssText = readFileSync(join(uiSrc, "styles.css"), "utf8");
  const expected = expectedRegistryThemeFromStyles(cssText);
  expected.theme = generateThemePayload(root);
  for (const item of registry.items ?? []) {
    const want = expected[item.name];
    if (!want) continue;
    if (want.cssVars) item.cssVars = want.cssVars;
    if (want.css) item.css = want.css;
  }
  writeFileSync(registryPath, `${JSON.stringify(registry, null, 2)}\n`);
}

function runShadcnBuild() {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  execFileSync("pnpm", ["exec", "shadcn", "build", "registry.json", "-o", outDir], {
    cwd: root,
    stdio: "inherit",
  });
}

stageTransformedSources();
syncRegistryTheme();
runShadcnBuild();
